let currentLanguage = "es";

const menuButton = document.querySelector(".menu-toggle");
const nav = document.querySelector(".main-nav");
const languageButtons = document.querySelectorAll(".language-button");
const typewriter = document.querySelector(".typewriter");
const contactTypewriter = document.querySelector(".contact-typewriter");
const projectDialog = document.querySelector(".project-dialog");


/* =========================================
   CAMBIO DE IDIOMA
========================================= */

/**
 * @param {"es" | "en"} language
 */
function setLanguage(language) {
  if (!translations[language]) return;

  currentLanguage = language;
  const text = translations[language];

  document.documentElement.lang = language;
  document.title = text.pageTitle;

  const descriptionMeta = document.querySelector('meta[name="description"]');

  if (descriptionMeta) {
    descriptionMeta.setAttribute("content", text.metaDescription);
  }

  document.querySelectorAll("[data-i18n]").forEach((element) => {
    const key = element.dataset.i18n;

    if (Object.prototype.hasOwnProperty.call(text, key)) {
      if (key === "aboutLead") {
        element.innerHTML = text[key];
      } else {
        element.textContent = text[key];
      }
    }
  });

  // Actualizar tarjetas de proyectos
  document.querySelectorAll(".project-card[data-project-key]").forEach((card) => {
    const key = card.dataset.projectKey;

    const titleKey = {
      identity: "projectIdentity",
      digital: "projectDigital",
      social: "projectSocial",
      packaging: "projectPackaging",
      personal: "projectPersonal"
    }[key];

    card.dataset.projectTitle = text[titleKey];
    card.dataset.projectType = text.projectPlaceholder;
    card.dataset.projectDescription = text.projectDescriptions[key];

    const cardTitle = card.querySelector(".project-card-title");
    const cardType = card.querySelector(".project-type");

    if (cardTitle) cardTitle.textContent = text[titleKey];
    if (cardType) cardType.textContent = text.projectPlaceholder;
  });

  // Actualizar animación principal
  if (typewriter) {
    typewriter.dataset.phrases = JSON.stringify(text.heroPhrases);
    typewriter.setAttribute("aria-label", text.heroPhrases.join(" "));
    typewriter.textContent = text.heroPhrases[0];

    restartHeroTypewriter();
  }

  // Actualizar animación de contacto
  if (contactTypewriter) {
    contactTypewriter.setAttribute("aria-label", text.contactAria);

    restartContactTypewriter();
  }

  const closeButton = document.querySelector(".project-dialog-close");

  if (closeButton) {
    closeButton.setAttribute("aria-label", text.closeProject);
  }

  const wordmark = document.querySelector(".header-inner > .wordmark");

  if (wordmark) {
    wordmark.setAttribute("aria-label", text.homeLabel);
  }

  // Actualizar botones de idioma
  languageButtons.forEach((button) => {
    const active = button.dataset.language === language;

    button.classList.toggle("is-active", active);
    button.setAttribute("aria-pressed", String(active));

    button.setAttribute(
      "aria-label",
      button.dataset.language === "es"
        ? text.languageEs
        : text.languageEn
    );
  });

  // Actualizar menú
  if (menuButton) {
    menuButton.setAttribute(
      "aria-label",
      nav && nav.classList.contains("is-open")
        ? text.menuClose
        : text.menuOpen
    );
  }

  // Actualizar modal si está abierto
  if (projectDialog && projectDialog.open) {
    const selectedCard = document.querySelector(
      `.project-card[data-project-key="${projectDialog.dataset.projectKey}"]`
    );

    if (selectedCard) {
      updateProjectDialog(selectedCard);
    }
  }
}


/* =========================================
   ANIMACIÓN DEL TEXTO PRINCIPAL
========================================= */

let heroTimer = null;
let heroPhraseIndex = 0;
let heroCharacterIndex = 0;
let heroDeleting = false;

function restartHeroTypewriter() {
  if (!typewriter) return;

  window.clearTimeout(heroTimer);

  heroPhraseIndex = 0;
  heroCharacterIndex = 0;
  heroDeleting = false;

  const phrases = translations[currentLanguage].heroPhrases;

  const reduceMotion = window.matchMedia(
    "(prefers-reduced-motion: reduce)"
  ).matches;

  if (reduceMotion) {
    typewriter.textContent = phrases[0];
    return;
  }

  typewriter.textContent = "";

  const animate = () => {
    const currentPhrases = translations[currentLanguage].heroPhrases;
    const phrase = currentPhrases[heroPhraseIndex];

    typewriter.textContent = phrase.slice(0, heroCharacterIndex);

    let delay = heroDeleting ? 42 : 78;

    if (!heroDeleting && heroCharacterIndex < phrase.length) {
      heroCharacterIndex++;

    } else if (heroDeleting && heroCharacterIndex > 0) {
      heroCharacterIndex--;

    } else if (!heroDeleting) {
      heroDeleting = true;
      delay = 1350;

    } else {
      heroDeleting = false;
      heroPhraseIndex = (heroPhraseIndex + 1) % currentPhrases.length;
      delay = 300;
    }

    heroTimer = window.setTimeout(animate, delay);
  };

  animate();
}


/* =========================================
   ANIMACIÓN DEL TEXTO DE CONTACTO
========================================= */

let contactTimer = null;

function restartContactTypewriter() {
  if (!contactTypewriter) return;

  window.clearTimeout(contactTimer);

  const firstLine = contactTypewriter.querySelector(
    ".contact-typewriter-first"
  );

  const secondLine = contactTypewriter.querySelector(
    ".contact-typewriter-second"
  );

  if (!firstLine || !secondLine) return;

  const text = translations[currentLanguage];

  const firstText = text.contactFirst;
  const secondText = text.contactSecond;

  const reduceMotion = window.matchMedia(
    "(prefers-reduced-motion: reduce)"
  ).matches;

  if (reduceMotion) {
    firstLine.textContent = firstText;
    secondLine.textContent = secondText;
    return;
  }

  let line = 0;
  let character = 0;
  let deleting = false;

  firstLine.textContent = "";
  secondLine.textContent = "";

  const animate = () => {
    const currentText = line === 0
      ? translations[currentLanguage].contactFirst
      : translations[currentLanguage].contactSecond;

    const target = line === 0 ? firstLine : secondLine;

    target.textContent = currentText.slice(0, character);

    let delay = deleting ? 50 : 95;

    if (!deleting && character < currentText.length) {
      character++;

    } else if (!deleting) {
      if (line === 0) {
        line = 1;
        character = 0;
        delay = 240;
      } else {
        delay = 1500;
        deleting = true;
      }

    } else if (character > 0) {
      character--;

    } else if (line === 1) {
      line = 0;
      character = translations[currentLanguage].contactFirst.length;
      delay = 160;

    } else {
      deleting = false;
      character = 0;
      delay = 400;
    }

    contactTimer = window.setTimeout(animate, delay);
  };

  animate();
}


/* =========================================
   MENÚ PARA CELULARES
========================================= */

if (menuButton && nav) {
  menuButton.addEventListener("click", () => {
    const open = nav.classList.toggle("is-open");

    menuButton.setAttribute("aria-expanded", String(open));

    menuButton.setAttribute(
      "aria-label",
      open
        ? translations[currentLanguage].menuClose
        : translations[currentLanguage].menuOpen
    );
  });

  nav.querySelectorAll("a").forEach((link) => {
    link.addEventListener("click", () => {
      nav.classList.remove("is-open");

      menuButton.setAttribute("aria-expanded", "false");

      menuButton.setAttribute(
        "aria-label",
        translations[currentLanguage].menuOpen
      );
    });
  });
}


